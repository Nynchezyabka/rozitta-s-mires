/** Suggests up to `max` icons for a name, best first. Empty when nothing matches. */
export function suggestIcons(name: string, max = 6): string[] {
  const words = name.toLowerCase().replace(/ё/g, "е").split(/[^a-zа-я0-9]+/i).filter(Boolean);
  const text = words.join(" ");
  const out: string[] = [];
  for (const [stems, icons] of HINTS) {
    const hit = stems.some((s) => {
      const st = s.replace(/ё/g, "е");
      return st.includes(" ") ? text.includes(st) : words.some((w) => w.startsWith(st));
    });
    if (hit) for (const i of icons) if (!out.includes(i)) out.push(i);
  }
  return out.slice(0, max);
}
